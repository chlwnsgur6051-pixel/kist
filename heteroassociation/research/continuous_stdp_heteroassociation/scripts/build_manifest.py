"""Refresh file hashes and source-path provenance for this archived package."""
from __future__ import annotations

import csv
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    "src/continuous_stdp_experiment.py": "continuous_stdp_experiment.py",
    "src/reference_20261102_105031.zip":
        "results/correction_learning_1ms4ms/20261102_105031/npz/{original,modified}_K10_seed0_Basic_Correction.npz + csv/presentation_orders.csv (repacked)",
    "src/reference_nonnegative_weight_results.zip":
        "results/basic_correction_nonnegative_comparison/epoch_accuracy.csv (format-only adapter)",
    "datasets/original_K10.npz": "my_research/reference/datasets/Original.npz",
    "datasets/modified_K10.npz": "my_research/reference/datasets/B.npz",
    "references/previous_final_weights.npz":
        "results/basic_correction_nonnegative_comparison/final_weights.npz",
}


def main() -> None:
    rows = []
    for file in sorted(ROOT.rglob("*")):
        if not file.is_file() or file.name == "artifact_manifest.csv" or "__pycache__" in file.parts:
            continue
        rel = file.relative_to(ROOT).as_posix()
        if rel.startswith("results/csv/") or rel.startswith("results/checkpoints/"):
            source = "complete replay of bundled continuous_stdp_experiment.py"
        else:
            source = SOURCES.get(rel, "authored document or generated by bundled scripts")
        rows.append({"path": rel, "bytes": file.stat().st_size,
                     "sha256": hashlib.sha256(file.read_bytes()).hexdigest(),
                     "source": source})
    with (ROOT / "artifact_manifest.csv").open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["path", "bytes", "sha256", "source"],
                                lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    print(f"Recorded {len(rows)} artifacts")


if __name__ == "__main__":
    main()
